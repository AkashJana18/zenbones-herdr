#!/usr/bin/env bash
# shared helpers for zenbones herdr plugin

THEME_ROOT="${HERDR_PLUGIN_ROOT:-$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)}"
CONFIG_PATH="${HERDR_CONFIG_PATH:-$HOME/.config/herdr/config.toml}"
STATE_DIR="${HERDR_PLUGIN_STATE_DIR:-${XDG_STATE_HOME:-$HOME/.local/state}/herdr-zenbones}"
APPLIED_FILE="$STATE_DIR/applied"
INDEX_FILE="$THEME_ROOT/themes/index.txt"

die() { printf '%s\n' "$*" >&2; exit 1; }

darken_hex() {
  local hex="${1#\#}" p="$2" r g b
  r=$((16#${hex:0:2})); g=$((16#${hex:2:2})); b=$((16#${hex:4:2}))
  r=$(( r * (100 - p) / 100 )); g=$(( g * (100 - p) / 100 )); b=$(( b * (100 - p) / 100 ))
  (( r < 0 )) && r=0; (( g < 0 )) && g=0; (( b < 0 )) && b=0
  printf '#%02x%02x%02x\n' "$r" "$g" "$b"
}

lighten_hex() {
  local hex="${1#\#}" p="$2" r g b
  r=$((16#${hex:0:2})); g=$((16#${hex:2:2})); b=$((16#${hex:4:2}))
  r=$(( r + (255 - r) * p / 100 )); g=$(( g + (255 - g) * p / 100 )); b=$(( b + (255 - b) * p / 100 ))
  (( r > 255 )) && r=255; (( g > 255 )) && g=255; (( b > 255 )) && b=255
  printf '#%02x%02x%02x\n' "$r" "$g" "$b"
}

ensure_config_exists() {
  if [ ! -f "$CONFIG_PATH" ]; then
    mkdir -p "$(dirname "$CONFIG_PATH")"
    printf '# herdr config — generated by zenbones plugin\nonboarding = false\n\n' > "$CONFIG_PATH"
  fi
}

resolve_theme() {
  local slug="$1"
  local file="$THEME_ROOT/themes/$slug"
  [ -f "$file" ] && echo "$file" || die "theme not found: $slug (try: $(ls "$THEME_ROOT/themes/" | grep -v index.txt | tr '\n' ' '))"
}

list_themes() {
  if [ -f "$INDEX_FILE" ]; then
    cat "$INDEX_FILE"
  else
    ls "$THEME_ROOT/themes/" | grep -v '^index\.txt$'
  fi
}
