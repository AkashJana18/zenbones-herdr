#Requires -Version 5.1
Set-StrictMode -Version Latest
$ErrorActionPreference = "Stop"

$ConfigPath = if ($env:HERDR_CONFIG_PATH) { $env:HERDR_CONFIG_PATH } else { Join-Path $HOME ".config/herdr/config.toml" }
$PluginRoot = if ($env:HERDR_PLUGIN_ROOT) { $env:HERDR_PLUGIN_ROOT } else { Split-Path -Parent (Split-Path -Parent $PSCommandPath) }
$StateDir = if ($env:HERDR_PLUGIN_STATE_DIR) { $env:HERDR_PLUGIN_STATE_DIR } else { Join-Path $HOME ".local/state/herdr-zenwritten" }
$AppliedFile = Join-Path $StateDir "applied"

function Fail($msg) { Write-Error $msg; exit 1 }

function Darken-Hex($hex, $p) {
    $hex = $hex.TrimStart('#')
    $r = [Convert]::ToInt32($hex.Substring(0,2),16)
    $g = [Convert]::ToInt32($hex.Substring(2,2),16)
    $b = [Convert]::ToInt32($hex.Substring(4,2),16)
    $r = [Math]::Max(0, [int]($r * (100 - $p) / 100))
    $g = [Math]::Max(0, [int]($g * (100 - $p) / 100))
    $b = [Math]::Max(0, [int]($b * (100 - $p) / 100))
    return "#{0:x2}{1:x2}{2:x2}" -f $r,$g,$b
}

function Get-PaletteValue($file, $key) {
    if ($key -like "p*") {
        $n = $key.Substring(1)
        $line = Select-String -Path $file -Pattern "^\s*palette\s*=\s*$n\s*=" | Select-Object -First 1
        if ($line) { return ($line.Line -split "=",2)[1].Trim() }
    } else {
        $line = Select-String -Path $file -Pattern "^\s*$key\s*=" | Select-Object -First 1
        if ($line) { return ($line.Line -split "=",2)[1].Trim() }
    }
    return $null
}

function Convert-PaletteToTokens($file) {
    $p0 = Get-PaletteValue $file "p0"; if (-not $p0) { Fail "not a valid palette: $file (missing palette 0)" }
    $bg = Get-PaletteValue $file "background"; $fg = Get-PaletteValue $file "foreground"
    $sel = Get-PaletteValue $file "selection-background"
    $p1 = Get-PaletteValue $file "p1"; $p2 = Get-PaletteValue $file "p2"; $p3 = Get-PaletteValue $file "p3"
    $p4 = Get-PaletteValue $file "p4"; $p5 = Get-PaletteValue $file "p5"; $p6 = Get-PaletteValue $file "p6"
    $p7 = Get-PaletteValue $file "p7"; $p8 = Get-PaletteValue $file "p8"; $p9 = Get-PaletteValue $file "p9"
    if (-not $sel) { $sel = $p0 }
    if (-not $p8) { $p8 = $p0 }
    if (-not $p9) { $p9 = $p3 }
    if (-not $bg) { Fail "missing background in $file" }
    if (-not $fg) { Fail "missing foreground in $file" }
    $sidebar = Darken-Hex $bg 12
    $dim = Darken-Hex $bg 8
    $lines = @(
        "panel_bg=$bg",
        "sidebar_bg=$sidebar",
        "active_row_bg=$p0",
        "selection_bg=$sel",
        "surface0=$p0",
        "surface1=$p8",
        "surface_dim=$dim",
        "overlay0=$p8",
        "overlay1=$p7",
        "text=$fg",
        "subtext0=$p7",
        "accent=$p4",
        "mauve=$p5",
        "green=$p2",
        "yellow=$p3",
        "red=$p1",
        "blue=$p4",
        "teal=$p6",
        "peach=$p9"
    )
    return $lines
}

function Ensure-ConfigExists {
    if (-not (Test-Path $ConfigPath)) {
        New-Item -ItemType Directory -Force -Path (Split-Path $ConfigPath) | Out-Null
        Set-Content -Path $ConfigPath -Value "# herdr config — generated by zenwritten`nonboarding = false`n" -Encoding UTF8
    }
}

function Resolve-Palette($name) {
    switch ($name) {
        "light" { return Join-Path $PluginRoot "themes/zenwritten-light" }
        "zenwritten-light" { return Join-Path $PluginRoot "themes/zenwritten-light" }
        "dark" { return Join-Path $PluginRoot "themes/zenwritten-dark" }
        "zenwritten-dark" { return Join-Path $PluginRoot "themes/zenwritten-dark" }
        default { return Join-Path $PluginRoot "themes/$name" }
    }
}

function Write-CustomBlock($cfg, $tokens) {
    $content = Get-Content -Raw -Path $cfg -ErrorAction SilentlyContinue
    if (-not $content) { $content = "" }
    # remove existing [theme.custom] and [theme.custom.*]
    $lines = Get-Content -Path $cfg -ErrorAction SilentlyContinue
    if (-not $lines) { $lines = @() }
    $out = @()
    $skip = $false
    foreach ($line in $lines) {
        if ($line -match "^\[theme\.custom\]$" -or $line -match "^\[theme\.custom\.") { $skip = $true; continue }
        if ($skip -and $line -match "^\[") { $skip = $false }
        if (-not $skip) { $out += $line }
    }
    $out += ""
    $out += "[theme.custom]"
    foreach ($t in $tokens) {
        $kv = $t -split "=",2
        $out += "$($kv[0]) = `"$($kv[1])`""
    }
    Set-Content -Path $cfg -Value ($out -join "`n") -Encoding UTF8
}

function Write-ModeBlock($cfg, $mode, $tokens) {
    $header = "[theme.custom.$mode]"
    $lines = Get-Content -Path $cfg -ErrorAction SilentlyContinue
    if (-not $lines) { $lines = @() }
    $out = @()
    $skip = $false
    foreach ($line in $lines) {
        if ($line -eq $header) { $skip = $true; continue }
        if ($skip -and $line -match "^\[") { $skip = $false }
        if (-not $skip) { $out += $line }
    }
    $out += ""
    $out += $header
    foreach ($t in $tokens) {
        $kv = $t -split "=",2
        $out += "$($kv[0]) = `"$($kv[1])`""
    }
    Set-Content -Path $cfg -Value ($out -join "`n") -Encoding UTF8
}

function Ensure-ThemeAuto($cfg, $val) {
    $content = Get-Content -Raw -Path $cfg -ErrorAction SilentlyContinue
    if ($content -notmatch "(?m)^\[theme\]") {
        Add-Content -Path $cfg -Value "`n[theme]`nname = `"catppuccin`"" -Encoding UTF8
    }
    $lines = Get-Content -Path $cfg
    $out = @()
    $inTheme = $false
    $hasAuto = $false
    foreach ($line in $lines) {
        if ($line -match "^\[theme\]$") { $inTheme = $true; $out += $line; continue }
        if ($line -match "^\[") { $inTheme = $false }
        if ($inTheme -and $line -match "^\s*auto_switch\s*=") {
            $out += "auto_switch = $val"
            $hasAuto = $true
            continue
        }
        $out += $line
    }
    if (-not $hasAuto) {
        $tmp = @()
        foreach ($line in $out) {
            $tmp += $line
            if ($line -match "^\[theme\]$") { $tmp += "auto_switch = $val" }
        }
        $out = $tmp
    }
    Set-Content -Path $cfg -Value ($out -join "`n") -Encoding UTF8
    if ($val -eq "true") {
        $c2 = Get-Content -Raw -Path $cfg
        if ($c2 -notmatch "dark_name") {
            $lines2 = Get-Content -Path $cfg
            $out2 = @()
            foreach ($line in $lines2) {
                $out2 += $line
                if ($line -match "^\[theme\]$") { $out2 += 'dark_name = "catppuccin"' }
            }
            Set-Content -Path $cfg -Value ($out2 -join "`n") -Encoding UTF8
        }
        $c3 = Get-Content -Raw -Path $cfg
        if ($c3 -notmatch "light_name") {
            $lines3 = Get-Content -Path $cfg
            $out3 = @()
            foreach ($line in $lines3) {
                $out3 += $line
                if ($line -match "^\[theme\]$") { $out3 += 'light_name = "catppuccin-latte"' }
            }
            Set-Content -Path $cfg -Value ($out3 -join "`n") -Encoding UTF8
        }
    }
}

function Apply-Single($slug) {
    $palette = Resolve-Palette $slug
    if (-not (Test-Path $palette)) { Fail "palette not found: $palette" }
    $tokens = Convert-PaletteToTokens $palette
    Ensure-ConfigExists
    $stamp = Get-Date -Format "yyyyMMdd"
    $bak = "$ConfigPath.bak-$stamp"
    if (-not (Test-Path $bak)) { Copy-Item $ConfigPath $bak -ErrorAction SilentlyContinue }
    # clear mode blocks
    $lines = Get-Content -Path $ConfigPath -ErrorAction SilentlyContinue
    if ($lines) {
        $out = @(); $skip=$false
        foreach ($line in $lines) {
            if ($line -match "^\[theme\.custom\.light\]$" -or $line -match "^\[theme\.custom\.dark\]$") { $skip=$true; continue }
            if ($skip -and $line -match "^\[") { $skip=$false }
            if (-not $skip) { $out += $line }
        }
        Set-Content -Path $ConfigPath -Value ($out -join "`n") -Encoding UTF8
    }
    Write-CustomBlock $ConfigPath $tokens
    Ensure-ThemeAuto $ConfigPath "false"
    New-Item -ItemType Directory -Force -Path $StateDir | Out-Null
    Set-Content -Path $AppliedFile -Value $slug -Encoding UTF8
    try { & herdr server reload-config | Out-Null } catch {}
    Write-Host "Applied Zenwritten $slug -> $ConfigPath"
}

function Apply-Auto {
    $lp = Resolve-Palette "light"; $dp = Resolve-Palette "dark"
    if (-not (Test-Path $lp)) { Fail "missing light palette" }
    if (-not (Test-Path $dp)) { Fail "missing dark palette" }
    $lt = Convert-PaletteToTokens $lp; $dt = Convert-PaletteToTokens $dp
    Ensure-ConfigExists
    $stamp = Get-Date -Format "yyyyMMdd"
    $bak = "$ConfigPath.bak-$stamp"
    if (-not (Test-Path $bak)) { Copy-Item $ConfigPath $bak -ErrorAction SilentlyContinue }
    Write-CustomBlock $ConfigPath $lt
    Write-ModeBlock $ConfigPath "light" $lt
    Write-ModeBlock $ConfigPath "dark" $dt
    Ensure-ThemeAuto $ConfigPath "true"
    New-Item -ItemType Directory -Force -Path $StateDir | Out-Null
    Set-Content -Path $AppliedFile -Value "auto" -Encoding UTF8
    try { & herdr server reload-config | Out-Null } catch {}
    Write-Host "Applied Zenwritten auto (light+dark) -> $ConfigPath"
}

function Do-Toggle {
    $cur = ""
    if (Test-Path $AppliedFile) { $cur = (Get-Content $AppliedFile -ErrorAction SilentlyContinue).Trim() }
    switch ($cur) {
        "light" { Apply-Single "dark" }
        "zenwritten-light" { Apply-Single "dark" }
        "dark" { Apply-Single "light" }
        "zenwritten-dark" { Apply-Single "light" }
        "auto" { Apply-Single "light" }
        default {
            if ((Get-Content $ConfigPath -ErrorAction SilentlyContinue | Select-String "#191919")) { Apply-Single "light" } else { Apply-Single "dark" }
        }
    }
}

$cmd = $args[0]
switch ($cmd) {
    "light" { Apply-Single "light" }
    "dark" { Apply-Single "dark" }
    "auto" { Apply-Auto }
    "toggle" { Do-Toggle }
    default {
        if (-not $cmd) {
            Write-Host "Usage: apply.ps1 light|dark|auto|toggle"
        } else {
            Fail "unknown command: $cmd (try: light, dark, auto, toggle)"
        }
    }
}
